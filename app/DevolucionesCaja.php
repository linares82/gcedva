<?php

namespace App;

use Illuminate\Database\Eloquent\Model;
use App\Traits\GetAllDataTrait;
use App\Traits\RelationManagerTrait;
use Illuminate\Database\Eloquent\SoftDeletes;

class DevolucionesCaja extends Model
{
	use RelationManagerTrait, GetAllDataTrait;
	use SoftDeletes;

	public function __construct(array $attributes = array())
	{
		parent::__construct($attributes);
		$this->addRelationApp(new \App\MotivosDevCaja, 'name');  // generated by relation command - MotivosDevCaja,DevolucionesCaja
		$this->addRelationApp(new \App\Grado, 'name');  // generated by relation command - Grado,DevolucionesCaja
		$this->addRelationApp(new \App\CajaConcepto, 'name');  // generated by relation command - CajaConcepto,DevolucionesCaja
		$this->addRelationApp(new \App\Plantel, 'razon');  // generated by relation command - Plantel,DevolucionesCaja
		$this->addRelationApp(new \App\Cliente, 'nombre');  // generated by relation command - Cliente,DevolucionesCaja
		$this->addRelationApp(new \App\Caja, 'consecutivo');  // generated by relation command - Caja,DevolucionesCaja
		$this->addRelationApp(new \App\StDevCaja, 'name');  // generated by relation command - StDevCaja,DevolucionesCaja

	}

	//Mass Assignment
	protected $fillable = [
		'caja_id',
		'cliente_id',
		'plantel_id',
		'monto',
		'caja_concepto_id',
		'grado_id',
		'motivos_dev_caja_id',
		'st_dev_caja_id',
		'vobo',
		'obs',
		'usu_alta_id',
		'usu_mod_id'
	];

	public function usu_alta()
	{
		return $this->hasOne('App\User', 'id', 'usu_alta_id');
	} // end

	public function usu_mod()
	{
		return $this->hasOne('App\User', 'id', 'usu_mod_id');
	} // end


	protected $dates = ['deleted_at'];

	// generated by relation command - MotivosDevCaja,DevolucionesCaja - start
	public function motivosDevCaja()
	{
		return $this->belongsTo('App\MotivosDevCaja');
	} // end

	// generated by relation command - Grado,DevolucionesCaja - start
	public function grado()
	{
		return $this->belongsTo('App\Grado');
	} // end

	// generated by relation command - CajaConcepto,DevolucionesCaja - start
	public function cajaConcepto()
	{
		return $this->belongsTo('App\CajaConcepto');
	} // end

	// generated by relation command - Plantel,DevolucionesCaja - start
	public function plantel()
	{
		return $this->belongsTo('App\Plantel');
	} // end

	// generated by relation command - Cliente,DevolucionesCaja - start
	public function cliente()
	{
		return $this->belongsTo('App\Cliente');
	} // end

	// generated by relation command - Caja,DevolucionesCaja - start
	public function caja()
	{
		return $this->belongsTo('App\Caja');
	} // end

	// generated by relation command - StDevCaja,DevolucionesCaja - start
	public function stDevCaja()
	{
		return $this->belongsTo('App\StDevCaja');
	} // end


}
